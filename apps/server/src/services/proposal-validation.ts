/** Validate agent payloads before storing or applying a proposal. No coercions. */
import { z } from "zod";
import type { ProposalType } from "@visua/core";
import { isWorkDate } from "./work.ts";

const Id = z.string().trim().min(1).max(300);
const Title = z.string().trim().min(1).max(200);
const Requirements = z.array(Id).max(2000).default([]);
const Level = z.number().int().min(0).max(4);
const WorkDate = z.string().refine(isWorkDate, "Must be a valid calendar date (YYYY-MM-DD)");
const TaskKind = z.enum(["governance", "policy", "procedure", "technical", "evidence", "training", "assessment", "vendor", "monitoring"]);
const TaskStatus = z.enum(["backlog", "todo", "in-progress", "in-review", "done", "blocked"]);
const Assignee = z.discriminatedUnion("type", [
  z.object({ type: z.literal("person"), id: Id, name: z.string().max(200).optional() }).strict(),
  z.object({ type: z.literal("agent"), id: Id, name: Title }).strict(),
  z.object({ type: z.literal("external"), id: z.literal("external"), name: Title }).strict(),
]);
const Impact = z.enum(["low", "moderate", "high"]);
const Rating = z.number().int().min(1).max(5);
const Family = z.enum(["csf", "soc2", "rmf", "ai", "law"]);
const Confidence = z.enum(["low", "medium", "high"]);
const Projection = z.object({
  nodeId: Id, kind: z.literal("implementation-projection"), version: z.literal(1),
  targetFamily: Family, suggested: Level, confidence: Confidence,
  reasons: z.array(z.string().max(2000)).max(20),
  sources: z.array(z.object({
    nodeId: Id, family: Family, level: Level, levelLabel: z.string().max(200), projectedLevel: Level,
    relationship: z.enum(["equivalent", "subset-of", "superset-of", "intersects-with", "related-to", "supports"]),
    authority: z.string().max(500), mappingSetId: Id,
    citation: z.object({ documentId: Id, page: z.number().int().positive().optional(), locator: z.string().max(1000).optional() }).strict(),
    status: z.enum(["final", "draft", "unreviewed", "superseded"]).optional(), strength: z.string().max(100).optional(),
  }).strict()).min(1).max(2000),
}).strict();
const Narrative = z.object({
  title: Title,
  kind: z.enum(["document", "screenshot", "configuration", "log", "report"]).default("document"),
  content: z.string().trim().min(1).max(500_000),
  requirementIds: Requirements,
  validDays: z.number().int().min(1).max(730).optional(),
}).strict();

const schemas = {
  "set-level": z.object({ nodeId: Id, current: Level, projection: Projection.optional() }).strict(),
  "set-target": z.object({ nodeId: Id, target: Level }).strict(),
  "set-applicability": z.object({ nodeId: Id, applicable: z.boolean(), rationale: z.string().trim().min(1).max(2000) }).strict(),
  "create-task": z.object({
    title: Title, description: z.string().max(20_000).default(""),
    kind: TaskKind.default("technical"), priority: z.enum(["critical", "high", "medium", "low"]).default("medium"),
    requirementIds: Requirements, dueDate: WorkDate.optional(), startDate: WorkDate.optional(),
    assignee: Assignee.optional(), effortHours: z.number().finite().min(0).max(100_000).optional(),
    checklist: z.array(z.string().trim().min(1).max(2000)).max(200).default([]),
  }).strict(),
  "update-task": z.object({
    taskId: Id, status: TaskStatus.optional(), requirementIds: z.array(Id).max(2000).optional(),
    assignee: Assignee.nullable().optional(), dueDate: WorkDate.nullable().optional(), startDate: WorkDate.nullable().optional(),
    completeChecklistItems: z.array(Id).max(200).optional(), note: z.string().max(20_000).optional(),
  }).strict().refine(value => Object.keys(value).some(key => key !== "taskId"), "A task update needs at least one change"),
  "create-evidence": z.union([z.object({ checkResultId: Id }).strict(), Narrative]),
  "review-evidence": z.object({
    evidenceId: Id, decision: z.enum(["accepted", "rejected"]), note: z.string().trim().max(2000).optional(),
    // These preconditions are generated by the service, compared immutably at
    // approval, and validated against the actual artifact by reviewEvidence.
    expectedScope: z.record(z.string(), z.unknown()).optional(), expectedReviewId: Id.nullable().optional(),
  }).strict().refine(value => value.decision !== "rejected" || !!value.note, "Rejecting evidence requires a reason"),
  "create-policy": z.object({ title: Title, body: z.string().trim().min(1).max(500_000), requirementIds: Requirements }).strict(),
  "create-risk": z.object({
    title: Title, description: z.string().max(10_000).default(""),
    likelihood: Rating.default(3), impact: Rating.default(3),
    treatment: z.enum(["mitigate", "accept", "transfer", "avoid"]).default("mitigate"),
    status: z.enum(["open", "treating", "accepted", "closed"]).default("open"),
    requirementIds: Requirements, owner: z.string().max(200).optional(),
  }).strict(),
  "set-rmf": z.object({
    systemName: Title.optional(), systemDescription: z.string().max(4000).optional(),
    informationTypes: z.array(z.object({ id: Id, name: Title, confidentiality: Impact, integrity: Impact, availability: Impact }).strict()).min(1).max(200).optional(),
    categorization: z.object({ confidentiality: Impact, integrity: Impact, availability: Impact, overall: Impact }).strict().optional(),
    baseline: Impact.optional(), privacyBaseline: z.boolean().optional(),
    tailoring: z.array(z.object({ nodeId: Id, action: z.enum(["add", "remove"]), rationale: z.string().trim().min(1).max(2000) }).strict()).max(2000).optional(),
  }).strict().refine(value => Object.keys(value).length > 0, "An RMF proposal needs at least one change"),
} satisfies Record<ProposalType, z.ZodType>;

export function parseProposalPayload(type: ProposalType, payload: unknown): Record<string, unknown> {
  if (!Object.hasOwn(schemas, type)) throw new Error("Unknown proposal type");
  if (payload && typeof payload === "object") {
    if (type === "set-rmf" && Object.hasOwn(payload, "authorization")) throw new Error("Agents cannot propose authorization decisions; use the system authorization workflow");
    if (type === "create-evidence" && "kind" in payload && ["automated-check", "attestation", "policy"].includes(String(payload.kind))) throw new Error("Agent narrative cannot claim automated-check, attestation or approved-policy evidence");
  }
  const parsed = schemas[type].safeParse(payload);
  if (!parsed.success) throw new Error(`Invalid ${type} proposal: ${z.prettifyError(parsed.error)}`);
  return parsed.data;
}

export function parseProposalEnvelope(input: unknown) {
  const parsed = z.object({
    type: z.enum(Object.keys(schemas) as [ProposalType, ...ProposalType[]]),
    title: Title, rationale: z.string().max(20_000), payload: z.record(z.string(), z.unknown()),
    confidence: Confidence, nodeIds: z.array(Id).max(2000),
    citations: z.array(z.object({
      documentId: Id, documentTitle: z.string().max(500), quote: z.string().trim().min(1).max(600),
      page: z.number().int().positive().optional(), locator: z.string().max(1000).optional(),
      chunkId: z.string().min(1).max(500).optional(), chunkSha256: z.string().regex(/^[a-f0-9]{64}$/).optional(),
    }).strict()).max(100),
  }).strict().safeParse(input);
  if (!parsed.success) throw new Error(`Invalid proposal: ${z.prettifyError(parsed.error)}`);
  return parsed.data;
}

/** Existing broad grants cannot silently authorize newly constrained types. */
export const SAFE_AUTONOMY_TYPES = ["create-task", "create-evidence"] as const;
export function parseAutonomy(value: unknown): Partial<Record<ProposalType, boolean>> {
  const parsed = z.object({ "create-task": z.boolean().optional(), "create-evidence": z.boolean().optional() }).strict().safeParse(value);
  if (!parsed.success) throw new Error("Autonomy supports only creating tasks and filing immutable recorded checks");
  return parsed.data;
}

export function mayApplyAutonomously(type: ProposalType, payload: Record<string, unknown>, autonomy: Partial<Record<ProposalType, boolean>>): boolean {
  return autonomy[type] === true && (type === "create-task" || (type === "create-evidence" && typeof payload["checkResultId"] === "string" && Object.keys(payload).length === 1));
}
