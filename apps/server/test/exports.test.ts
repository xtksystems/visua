import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { Ajv } from "ajv";
import addFormats from "ajv-formats";
import { afterAll, afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { evidenceReviewScope, type OrganizationProfile, type RequirementNode } from "@visua/core";
import { FrameworkRegistry } from "@visua/frameworks";
import { createService } from "../src/context.ts";
import { captureExportSnapshot } from "../src/services/export-snapshot.ts";
import { actionPlanCsv, aiRmfProfileCsv, csfProfileCsv, evidenceIndexCsv, oscalPoam, oscalSsp, oscalUuid, readinessMarkdown, soc2PbcCsv, toCsv, OSCAL_SOURCE_PIN } from "../src/services/exports.ts";
import { testDatabase } from "./db.ts";

const registry = FrameworkRegistry.load();
const db = await testDatabase("exports");
const svc = await createService({ database: db.url, registry });
const CSF = "nist-csf-2.0", AI = "nist-ai-rmf", SOC = "aicpa-tsc-2017", RMF = "nist-sp-800-53-r5", LAW = "us-state-ai-laws";
const A = `${CSF}:PR.AA-01`, AC1 = `${RMF}:AC-1`, AC2 = `${RMF}:AC-2`;
const NOW = "2026-10-13T12:00:00.000Z";
const profile: OrganizationProfile = { industry: "saas", size: "11-50", dataTypes: [], drivers: [], environments: ["cloud"], maturityTier: 1, guidance: "guided", securityTeamSize: 1 };
let n = 0;
const fixture = (frameworks = [CSF, AI, SOC, RMF]) => svc.createWorkspace({ name: `Reports ${++n}`, profile, frameworks });
beforeEach(() => { vi.useFakeTimers({ toFake: ["Date"] }); vi.setSystemTime(new Date(NOW)); });
afterEach(() => { vi.restoreAllMocks(); vi.useRealTimers(); });
afterAll(async () => { await svc.store.close(); await db.cleanup(); });

// Exact unmodified official release schemas. strict:false allows annotations and
// alternative-type patterns generated by NIST; all actual keywords and formats run.
const ajv = new Ajv({ allErrors: true, strict: false, unicodeRegExp: true });
addFormats(ajv);
const schema = (name: string) => JSON.parse(readFileSync(new URL(`./fixtures/oscal/oscal_${name}_schema.json`, import.meta.url), "utf8"));
const validateSsp = ajv.compile(schema("ssp"));
const validatePoam = ajv.compile(schema("poam"));
const check = (validate: typeof validateSsp, document: unknown) => expect(validate(document), JSON.stringify(validate.errors, null, 2)).toBe(true);

// These are outputs under inspection; property shapes are enforced by the schemas above.
const sspBody = (doc: Record<string, unknown>) => doc["system-security-plan"] as Record<string, any>;
const poamBody = (doc: Record<string, unknown>) => doc["plan-of-action-and-milestones"] as Record<string, any>;

describe(`snapshot-backed reports (${db.dialect})`, () => {
  it("renders every report solely from a supplied snapshot after database reads become unavailable", async () => {
    const ws = await fixture();
    const snap = await captureExportSnapshot(svc, ws);
    vi.spyOn(svc, "workspace").mockRejectedValue(new Error("Live workspace read"));
    vi.spyOn(svc, "score").mockRejectedValue(new Error("Live score read"));
    vi.spyOn(svc.store, "atomic").mockRejectedValue(new Error("Live transaction"));
    vi.spyOn(svc.store, "db").mockImplementation(() => { throw new Error("Live SQL read"); });
    for (const report of [actionPlanCsv, aiRmfProfileCsv, csfProfileCsv, evidenceIndexCsv, readinessMarkdown, soc2PbcCsv]) expect(await report(svc, ws, snap)).toBeTruthy();
    check(validateSsp, await oscalSsp(svc, ws, snap));
    check(validatePoam, await oscalPoam(svc, ws, snap));
  });

  it("keeps fixed-asOf reports and subject identifiers stable while separating capture metadata", async () => {
    const ws = await fixture([RMF]);
    const first = await captureExportSnapshot(svc, ws, { asOf: NOW });
    const ssp = sspBody(await oscalSsp(svc, ws, first)), poam = poamBody(await oscalPoam(svc, ws, first));
    vi.setSystemTime(new Date("2026-10-13T13:00:00Z"));
    const second = await captureExportSnapshot(svc, ws, { asOf: NOW });
    const next = sspBody(await oscalSsp(svc, ws, second)), nextPoam = poamBody(await oscalPoam(svc, ws, second));
    expect(next.uuid).toBe(ssp.uuid);
    expect(next["control-implementation"]).toEqual(ssp["control-implementation"]);
    expect(next["system-implementation"]).toEqual(ssp["system-implementation"]);
    expect(nextPoam["poam-items"]).toEqual(poam["poam-items"]);
    expect(next.metadata["last-modified"]).not.toBe(ssp.metadata["last-modified"]);
    expect(next.metadata.props.filter((p: { name: string }) => p.name !== "records-captured-at")).toEqual(ssp.metadata.props.filter((p: { name: string }) => p.name !== "records-captured-at"));
    expect(await actionPlanCsv(svc, ws, first)).toBe(await actionPlanCsv(svc, ws, second));
    const reversed = { ...first, states: [...first.states].reverse(), tasks: [...first.tasks].reverse() };
    expect(await oscalSsp(svc, ws, reversed)).toEqual(await oscalSsp(svc, ws, first));
    expect(oscalUuid(ws.id, "system", "workspace")).toMatch(/^[\da-f]{8}-[\da-f]{4}-5[\da-f]{3}-[89ab][\da-f]{3}-[\da-f]{12}$/);
    expect(oscalUuid(ws.id, "system", "workspace")).not.toBe(oscalUuid("other-workspace", "system", "workspace"));
    expect(oscalUuid(ws.id, "system", "workspace")).not.toBe(oscalUuid(ws.id, "component", "workspace"));
  });

  it("uses asOf for expiry and accepted replacement lineage without treating the window as historical replay", async () => {
    const ws = await fixture([CSF]);
    const old = await svc.createEvidence(ws.id, { title: "Original proof", content: "one", requirementIds: [A], collectedAt: "2026-01-01", validUntil: "2026-10-13T12:00:01Z" });
    await svc.reviewEvidence(ws.id, old.id, "accepted", "fixture", undefined, evidenceReviewScope(old));
    const next = await svc.createEvidence(ws.id, { title: "Replacement proof", content: "two", requirementIds: [A], collectedAt: "2026-01-01", validUntil: "2026-10-13T12:00:01Z", supersedesId: old.id });
    await svc.reviewEvidence(ws.id, next.id, "accepted", "fixture", undefined, evidenceReviewScope(next));
    const snap = await captureExportSnapshot(svc, ws);
    const csv = await csfProfileCsv(svc, ws, snap);
    expect(csv).toContain("Replacement proof"); expect(csv).not.toContain("Original proof");
    expect(await evidenceIndexCsv(svc, ws, snap)).toContain("superseded");
    vi.setSystemTime(new Date("2026-10-13T12:00:02Z"));
    expect(await csfProfileCsv(svc, ws, snap)).toBe(csv);
    const expired = await captureExportSnapshot(svc, ws);
    expect(await csfProfileCsv(svc, ws, expired)).not.toContain("Replacement proof");
    expect(await evidenceIndexCsv(svc, ws, expired)).toContain("expired");
  });

  it.each([
    { framework: CSF, requirement: A, report: csfProfileCsv, implemented: "— implemented", verified: "— verified" },
    { framework: AI, requirement: registry.framework(AI)!.assessable[0]!.id, report: aiRmfProfileCsv, implemented: ",implemented,", verified: ",verified," },
    { framework: SOC, requirement: `${SOC}:CC6.1`, report: soc2PbcCsv, implemented: ",implemented,", verified: ",verified," },
  ])("applies the verification time boundary to $framework reports while preserving raw state", async ({ framework, requirement, report, implemented, verified }) => {
    vi.setSystemTime(new Date("2026-01-02T00:00:00.000Z"));
    const ws = await fixture([framework]);
    const evidence = await svc.createEvidence(ws.id, { title: "Earlier accepted proof", content: "proof", requirementIds: [requirement], collectedAt: "2026-01-01" });
    await svc.reviewEvidence(ws.id, evidence.id, "accepted", "fixture", undefined, evidenceReviewScope(evidence));
    const verifiedAt = "2026-10-13T11:00:00.000Z";
    vi.setSystemTime(new Date(verifiedAt));
    await svc.updateState(ws.id, requirement, { current: 3, target: 3, verifiedAt });
    vi.setSystemTime(new Date(NOW));
    for (const asOf of ["2026-10-13T10:59:59.999Z", verifiedAt, NOW]) {
      const snap = await captureExportSnapshot(svc, ws, { frameworkIds: [framework], asOf });
      const rawStates = structuredClone(snap.states);
      const csv = await report(svc, ws, snap);
      const readiness = await readinessMarkdown(svc, ws, snap);
      if (asOf < verifiedAt) {
        expect(csv).toContain(implemented);
        expect(csv).not.toContain(verified);
        expect(readiness).toContain("Verified: 0%");
        expect(readiness).toContain("implemented 1");
        expect(readiness).not.toContain("verified 1");
      } else {
        expect(csv).toContain(verified);
        expect(readiness).not.toContain("Verified: 0%");
        expect(readiness).toContain("verified 1");
      }
      expect(readiness).toContain("no historical revision replay");
      expect(snap.states).toEqual(rawStates);
      expect(snap.states.find(state => state.nodeId === requirement)).toMatchObject({ current: 3, target: 3, verifiedAt });
    }
  });

  it("keeps law-effective scope, explicit exclusions, and selected frameworks in readiness and POAM", async () => {
    const ws = await fixture([CSF, LAW]);
    const snap = await captureExportSnapshot(svc, ws, { frameworkIds: [LAW] });
    const lawIndex = registry.framework(LAW)!;
    const selectedNodes = lawIndex.assessable.slice(0, 3);
    const customNodes: RequirementNode[] = selectedNodes.map((node, i) => ({ ...node, attributes: { ...node.attributes, effective: i === 1 ? "2026-10-14" : "2026-01-01", until: i === 2 ? "2026-10-12" : undefined } }));
    const customRegistry = new FrameworkRegistry({ graphs: [{ framework: lawIndex.graph.framework, nodes: customNodes.map(node => ({ ...node, parentId: null, depth: 0 })) }], mappings: [], chunks: [], manifests: [] });
    const scoped = { ...snap, states: customNodes.map(node => ({ nodeId: node.id, current: 0, target: 3, priority: "medium" as const, applicable: true, updatedAt: NOW, updatedBy: "fixture" })) };
    const service = Object.assign(Object.create(svc), { registry: customRegistry }) as typeof svc;
    const markdown = await readinessMarkdown(service, ws, scoped);
    expect(markdown).toContain("across 1 in-scope"); expect(markdown).toContain("Not yet in effect"); expect(markdown).toContain("No longer in effect");
    expect(markdown).not.toContain("## NIST CSF");
    expect(poamBody(await oscalPoam(service, ws, scoped))["poam-items"]).toHaveLength(1);
    await expect(csfProfileCsv(svc, ws, snap)).rejects.toThrow("not selected");
  });

  it("provides concrete Visua-authored PBC asks for every skeleton criterion", async () => {
    const ws = await fixture([SOC]);
    const csv = await soc2PbcCsv(svc, ws);
    expect(csv).toContain("Evidence requested (Visua-authored)");
    for (const criterion of registry.framework(SOC)!.assessable) expect(csv).toContain(`Visua-authored request for ${criterion.code}: provide`);
    expect(csv).toContain("access inventories, authorization approvals");
    expect(csv).toContain("not AICPA text");
  });

  it.each(["=1+2", "+SUM(A1)", "-1+2", "@SUM(A1)", " \t=HYPERLINK(\"x\")", "\u0000\u000b=1", "\r\n=1", "\tplain text"])("neutralizes spreadsheet formula/control prefix %j", value => {
    const cell = toCsv([[value]]);
    expect(cell.startsWith("'") || cell.startsWith('"\'')).toBe(true);
  });
  it("preserves quoted text and multiline CSV cells", () => {
    expect(toCsv([["ordinary", 'a,"b"\nc']])).toBe('ordinary,"a,""b""\nc"\r\n');
  });
});

describe("OSCAL 1.1.2 truth and schema constraints", () => {
  it("uses an independent RFC 4122 version 5 vector and pins the actual installed source bytes", () => {
    // Independently generated with Python uuid.uuid5(uuid.NAMESPACE_URL, compact JSON tuple).
    expect(oscalUuid("workspace-vector", "system", "workspace")).toBe("b5551e9c-46b0-5284-b4e4-977db287ac81");
    const fileHash = (file: string) => createHash("sha256").update(readFileSync(new URL(`../../../corpus/nist-rmf/oscal/${file}`, import.meta.url))).digest("hex");
    expect(fileHash("NIST_SP-800-53_rev5_catalog.json")).toBe(OSCAL_SOURCE_PIN.catalogSha256);
    for (const [level, hash] of Object.entries(OSCAL_SOURCE_PIN.baselineSha256)) expect(fileHash(`NIST_SP-800-53_rev5_${level.toUpperCase()}-baseline_profile.json`)).toBe(hash);
  });

  it("pins unmodified official schemas and actually rejects invalid URI/date-time/UUID values", () => {
    for (const [name, expected] of [["ssp", "08d3faeb12f0fab7705dec15fb648c72400c7ab6ac0056222d49d21507e02a69"], ["poam", "906725163d767036c6189aec51252109b203214e121fc1acaff494b4d2dfbc04"]]) {
      const bytes = readFileSync(new URL(`./fixtures/oscal/oscal_${name}_schema.json`, import.meta.url));
      expect(createHash("sha256").update(bytes).digest("hex")).toBe(expected);
    }
    expect(ajv.compile({ type: "string", format: "uri" })("not a uri")).toBe(false);
    expect(ajv.compile({ type: "string", format: "date-time" })("2026-02-30T00:00:00Z")).toBe(false);
  });

  it("validates SSP and POAM, preserves zero and tailoring rationale, and supplies consistent system identity", async () => {
    const ws = await fixture([RMF]);
    const snap = await captureExportSnapshot(svc, ws);
    snap.workspace.frameworks.find(f => f.frameworkId === RMF)!.rmf!.tailoring.push({ nodeId: AC2, action: "remove", rationale: "Synthetic exclusion: system has no relevant account store" });
    const state = snap.states.find(s => s.nodeId === AC2)!; state.applicable = false; state.applicabilityRationale = "Synthetic exclusion: system has no relevant account store";
    const ssp = await oscalSsp(svc, ws, snap), poam = await oscalPoam(svc, ws, snap);
    check(validateSsp, ssp); check(validatePoam, poam);
    const body = sspBody(ssp);
    const ac1 = body["control-implementation"]["implemented-requirements"].find((r: { "control-id": string }) => r["control-id"] === "ac-1");
    expect(ac1["by-components"][0]["implementation-status"]).toMatchObject({ state: "not-implemented", remarks: expect.stringContaining("neither implementation nor a plan") });
    expect(body.metadata.remarks).toContain("Synthetic exclusion");
    expect(body.metadata.remarks).toContain(AC2);
    expect(body["import-profile"].href).toContain(OSCAL_SOURCE_PIN.commit); expect(body["import-profile"].href).not.toContain("/main/");
    expect(body["import-profile"].remarks).toContain("not a resolved tailored profile");
    expect(body["system-characteristics"]["system-ids"][0]).toEqual(poamBody(poam)["system-id"]);
    expect(body["system-implementation"].components[0].status.state).toBe(body["system-characteristics"].status.state);
    expect(poamBody(poam).metadata.remarks).toContain("Synthetic exclusion");
    const invalid = structuredClone(ssp); sspBody(invalid).uuid = "00000000-0000-7000-8000-000000000000";
    expect(validateSsp(invalid)).toBe(false);
  });

  it("returns explicit unavailable errors for empty scope and no gaps without inventing entities", async () => {
    const ws = await fixture([RMF]);
    const snap = await captureExportSnapshot(svc, ws);
    const empty = { ...snap, states: snap.states.map(state => ({ ...state, applicable: false, applicabilityRationale: "Synthetic exclusion" })) };
    await expect(oscalSsp(svc, ws, empty)).rejects.toThrow("OSCAL SSP unavailable");
    await expect(oscalPoam(svc, ws, empty)).rejects.toThrow("OSCAL POAM unavailable");
    const complete = { ...snap, states: snap.states.map(state => ({ ...state, current: state.target })) };
    await expect(oscalPoam(svc, ws, complete)).rejects.toThrow("no in-scope implementation gaps");
  });

  it("identifies the configured baseline independently from the recorded security impact", async () => {
    let ws = await fixture([RMF]);
    ws = await svc.categorizeSystem(ws.id, { informationTypes: [{ id: "records", name: "Test records", confidentiality: "high", integrity: "moderate", availability: "low" }] });
    const rmf = ws.frameworks.find(framework => framework.frameworkId === RMF)!.rmf!;
    ws = await svc.enableFramework(ws.id, RMF, { rmf: { ...rmf, baseline: "low" } });
    const snap = await captureExportSnapshot(svc, ws, { frameworkIds: [RMF] });
    const document = await oscalSsp(svc, ws, snap);
    check(validateSsp, document);
    const body = sspBody(document);
    expect(body["import-profile"].href).toContain("NIST_SP-800-53_rev5_LOW-baseline_profile.json");
    expect(body.metadata.props).toContainEqual(expect.objectContaining({ name: "source-baseline-sha256", value: OSCAL_SOURCE_PIN.baselineSha256.low }));
    expect(body["control-implementation"].description).toContain("LOW baseline");
    expect(body["control-implementation"]["implemented-requirements"]).toHaveLength(149);
    expect(body["system-characteristics"]).toMatchObject({
      "security-sensitivity-level": "fips-199-high",
      "security-impact-level": {
        "security-objective-confidentiality": "fips-199-high",
        "security-objective-integrity": "fips-199-moderate",
        "security-objective-availability": "fips-199-low",
      },
    });
  });

  it.each([false, true])("reports a missing configured baseline explicitly (categorized: %s)", async categorized => {
    let ws = await fixture([RMF]);
    if (categorized) ws = await svc.categorizeSystem(ws.id, { informationTypes: [{ id: "records", name: "Test records", confidentiality: "high", integrity: "moderate", availability: "low" }] });
    const rmf = ws.frameworks.find(framework => framework.frameworkId === RMF)!.rmf!;
    ws = await svc.enableFramework(ws.id, RMF, { rmf: { ...rmf, baseline: undefined } });
    const snap = await captureExportSnapshot(svc, ws, { frameworkIds: [RMF] });
    await expect(oscalSsp(svc, ws, snap)).rejects.toThrow("no SP 800-53 baseline is configured");
  });
});
