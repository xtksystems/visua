import { startServer } from "../../../apps/server/src/server.ts";
const started = await startServer({env: {VISUA_PORT: "0", VISUA_SEED: "0", VISUA_SHUTDOWN_MS: "2000"}, database: ":memory:"});
const begin = Date.now();
const note = (data: unknown) => console.log(Date.now()-begin, data);
started.server.on("connection", s => { s.on("close", () => note("socket closed")); });
started.server.on("request", (_req, res) => { res.on("finish", () => note({finish: true, keepAlive: res.shouldKeepAlive})); });
started.server.on("close", () => note("server closed"));
const oldDrain = started.svc.drainRuns.bind(started.svc);
started.svc.drainRuns = async () => { note("runs draining"); await oldDrain(); note("runs drained"); };
const oldClose = started.svc.store.close.bind(started.svc.store);
started.svc.store.close = async () => { note("store closing"); await oldClose(); note("store closed"); };
let release!: () => void;
let enter!: () => void;
const entered = new Promise<void>(r => enter = r);
const held = new Promise<void>(r => release = r);
const original = started.svc.store.driver.query.bind(started.svc.store.driver);
started.svc.store.driver.query = async (sql, params) => { if(sql === "SELECT 1") { enter(); await held; } return original(sql, params); };
const address = started.server.address() as {port: number};
const request = fetch(`http://127.0.0.1:${address.port}/api/ready`);
await entered;
note("query entered");
const stopping = started.stop().catch(e => note(e.message));
release();
const response = await request;
await response.arrayBuffer();
note({received: response.status});
started.server.getConnections((err, count) => note({connections:count,err}));
await stopping;
